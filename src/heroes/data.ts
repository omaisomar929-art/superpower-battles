function buildHero(base: number, exponent: number): Hero {
  const key = `${base}-${exponent}`
  const seed = NAMES[key]
  if (!seed) {
    throw new Error(`Missing hero seed for ${key}`)
  }
  const power = calculatePower(base, exponent)
  return {
    id: `hero-${base}x${exponent}`,
    name: seed.name,
    base,
    exponent,
    power,
    expression: formatExpression(base, exponent),
    mainColor: seed.mainColor,
    secondaryColor: seed.secondaryColor,
    accentColor: seed.accentColor,
    costume: seed.costume,
    signatureAttack: seed.signatureAttack,
    defensiveAbility: seed.defensiveAbility,
    fightingStyle: seed.fightingStyle,
    victoryAnimation: seed.victoryAnimation,
    defeatAnimation: seed.defeatAnimation,
    visualEffect: seed.visualEffect,
    visuals: seed.visuals,
    tagline: seed.tagline,
  }
}

export const HEROES: Hero[] = (() => {
  const list: Hero[] = []
  for (let base = 1; base <= 10; base += 1) {
    for (let exponent = 1; exponent <= 5; exponent += 1) {
      list.push(buildHero(base, exponent))
    }
  }
  return list
})()

export function getHeroById(id: string): Hero | undefined {
  return HEROES.find((hero) => hero.id === id)
}

export function getHeroByPowerPair(base: number, exponent: number): Hero | undefined {
  return HEROES.find((hero) => hero.base === base && hero.exponent === exponent)
}

export function getRandomHeroes(count: number, excludeIds: string[] = []): Hero[] {
  const pool = HEROES.filter((hero) => !excludeIds.includes(hero.id))
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

